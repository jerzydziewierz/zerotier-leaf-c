#!/usr/bin/env bash
# Build the test vector generator against the reference core and write the
# vectors. Run on a build host (not the workstation), for example:
#   tests/oracle/gen.sh ~/ztl-ref/ZeroTierOne tests/vectors/reference.txt
# The first argument is the ZeroTier One source tree that ../grey_zerotier
# uses as reference (revision and patches: ../grey_zerotier/prepare.py).
set -eu
cd "$(dirname "$0")/../.."
ZT=${1:?ZeroTier One source tree}; OUT=${2:-tests/vectors/reference.txt}
B=$(mktemp -d); trap 'rm -rf "$B"' EXIT
SRC=""
for f in Packet Salsa20 Poly1305 Utils AES AES_aesni AES_armcrypto Identity ECC SHA512; do SRC="$SRC $ZT/node/$f.cpp"; done
g++ -std=c++17 -O2 -DZT_NO_TYPE_PUNNING -DZT_NO_UNALIGNED_ACCESS -DZT_NO_PEER_METRICS -DOMIT_JSON_SUPPORT \
	-I"$ZT/node" -I"$ZT/include" -I"$ZT/ext" tests/oracle/gen_vectors.cpp $SRC -o "$B/gen" -lpthread
{
	echo "# Test vectors from the reference: ZeroTier One $(sed -n 's/.*REVISION = "\(.*\)"/\1/p' ../grey_zerotier/prepare.py 2>/dev/null || echo unknown) with the patches of ../grey_zerotier/patches."
	echo "# Generated by tests/oracle/gen.sh; do not edit. Formats: see tests/oracle/gen_vectors.cpp."
	"$B/gen"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "$OUT: $(grep -c '^P' "$OUT") Poly1305, $(grep -c '^[ST]' "$OUT") Salsa20/12, $(grep -c '^A' "$OUT") packet vectors"
